//! Generates os/feature_private.h from per-domain feature-flag plists.
//!
//!     featureflags -o <dir> <domain>=<plist> [<domain>=<plist> ...]
//!
//! Each plist is a top-level dict whose keys are feature names. Each feature
//! is a dict with an `Enabled` boolean:
//!
//!     <key>posix_spawn_filtering</key>
//!     <dict><key>Enabled</key><false/></dict>
//!
//! The generated header provides:
//!
//!   os_feature_enabled_simple(domain, feature, fallback)
//!       the configured value if `feature` is in the domain's plist, else `fallback`
//!   os_feature_enabled(domain, feature)
//!       the configured value, else false
//!
//! Anything other than that plist shape is rejected, not guessed at.

use std::fs;
use std::path::Path;
use std::process::exit;

fn die(msg: &str) -> ! {
    eprintln!("featureflags: {msg}");
    exit(1);
}

/// Returns (feature name, enabled) pairs in file order.
fn parse_plist(src: &str, path: &str) -> Vec<(String, bool)> {
    let mut out = Vec::new();
    let mut rest = src;
    while let Some(k) = rest.find("<key>") {
        let after = &rest[k + "<key>".len()..];
        let kend = after
            .find("</key>")
            .unwrap_or_else(|| die(&format!("{path}: unterminated <key>")));
        let name = after[..kend].trim().to_string();
        let body = after[kend + "</key>".len()..].trim_start();
        let inner_all = body
            .strip_prefix("<dict>")
            .unwrap_or_else(|| die(&format!("{path}: '{name}' is not a feature dict")));
        let dend = inner_all
            .find("</dict>")
            .unwrap_or_else(|| die(&format!("{path}: unterminated dict for '{name}'")));
        let inner = &inner_all[..dend];

        let ek = inner
            .find("<key>Enabled</key>")
            .unwrap_or_else(|| die(&format!("{path}: feature '{name}' has no Enabled key")));
        let value = inner[ek + "<key>Enabled</key>".len()..].trim_start();
        let enabled = if value.starts_with("<true/>") {
            true
        } else if value.starts_with("<false/>") {
            false
        } else {
            die(&format!("{path}: feature '{name}' Enabled is not <true/> or <false/>"))
        };
        out.push((name, enabled));
        rest = &inner_all[dend + "</dict>".len()..];
    }
    out
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut outdir: Option<String> = None;
    let mut domains: Vec<(String, String)> = Vec::new();

    let mut i = 0;
    while i < args.len() {
        if args[i] == "-o" {
            i += 1;
            outdir = Some(args.get(i).cloned().unwrap_or_else(|| die("-o needs a directory")));
        } else {
            let Some((d, p)) = args[i].split_once('=') else {
                die(&format!("expected <domain>=<plist>, got '{}'", args[i]));
            };
            domains.push((d.to_string(), p.to_string()));
        }
        i += 1;
    }
    let outdir = outdir.unwrap_or_else(|| die("-o <dir> is required"));
    if domains.is_empty() {
        die("at least one <domain>=<plist> is required");
    }

    let mut out = String::new();
    out.push_str("/*\n * Generated by //tools/featureflags from the feature-flag plists.\n */\n");
    out.push_str("#ifndef __OS_FEATURE_PRIVATE_H\n#define __OS_FEATURE_PRIVATE_H\n\n");
    out.push_str("#include <stdbool.h>\n#include <string.h>\n\n");

    for (domain, path) in &domains {
        if !domain.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            die(&format!("domain '{domain}' is not a C identifier"));
        }
        let src = fs::read_to_string(path).unwrap_or_else(|e| die(&format!("reading {path}: {e}")));
        let flags = parse_plist(&src, path);
        out.push_str(&format!(
            "static inline bool\n__os_feature_config_{domain}(const char *name, bool fallback)\n{{\n"
        ));
        for (feature, enabled) in &flags {
            out.push_str(&format!(
                "\tif (strcmp(name, \"{feature}\") == 0) {{\n\t\treturn {};\n\t}}\n",
                if *enabled { "true" } else { "false" }
            ));
        }
        if flags.is_empty() {
            out.push_str("\t(void)name;\n");
        }
        out.push_str("\treturn fallback;\n}\n\n");
    }

    out.push_str("#define os_feature_enabled_simple(domain, feature, fallback) \\\n");
    out.push_str("\t__os_feature_config_##domain(#feature, (fallback))\n");
    out.push_str("#define os_feature_enabled(domain, feature) \\\n");
    out.push_str("\t__os_feature_config_##domain(#feature, false)\n\n");
    out.push_str("#endif /* __OS_FEATURE_PRIVATE_H */\n");

    let dir = Path::new(&outdir).join("os");
    fs::create_dir_all(&dir).unwrap_or_else(|e| die(&format!("creating {}: {e}", dir.display())));
    let file = dir.join("feature_private.h");
    fs::write(&file, out).unwrap_or_else(|e| die(&format!("writing {}: {e}", file.display())));
}
