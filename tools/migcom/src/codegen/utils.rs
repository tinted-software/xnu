pub fn write_identification(w: &mut dyn Write, opts: &Options) -> io::Result<()> {
    writeln!(w, "/*")?;
    writeln!(w, " * IDENTIFICATION:")?;
    writeln!(w, " * stub generated by {MIG_VERSION}")?;
    writeln!(w, " * OPTIONS: ")?;
    if opts.is_kernel_user {
        writeln!(w, " *\tKernelUser")?;
    }
    if opts.is_kernel_server {
        writeln!(w, " *\tKernelServer")?;
    }
    if !opts.use_msg_rpc {
        writeln!(w, " *\t-R (no RPC calls)")?;
    }
    writeln!(w, " */")
}

pub fn write_mig_external(w: &mut dyn Write) -> io::Result<()> {
    writeln!(w, "#ifdef\tmig_external")?;
    writeln!(w, "mig_external")?;
    writeln!(w, "#else")?;
    writeln!(w, "extern")?;
    writeln!(w, "#endif\t/* mig_external */")
}

pub fn write_import(w: &mut dyn Write, filename: &str) -> io::Result<()> {
    writeln!(w, "#include {filename}")
}

/// `WriteImplImports`
pub fn write_impl_imports(w: &mut dyn Write, stmts: &[Statement], isuser: bool) -> io::Result<()> {
    for stmt in stmts {
        if let Statement::Import { kind, filename } = stmt {
            let take = match kind {
                ImportKind::Import | ImportKind::IImport => true,
                ImportKind::SImport => !isuser,
                ImportKind::UImport => isuser,
                ImportKind::DImport => false,
            };
            if take {
                write_import(w, filename)?;
            }
        }
    }
    Ok(())
}

/// `WriteRCSDecl`
pub fn write_rcs_decl(w: &mut dyn Write, name: &str, rcs: &str) -> io::Result<()> {
    writeln!(w, "#ifndef\tlint")?;
    writeln!(w, "#if\tUseExternRCSId")?;
    writeln!(w, "const char {name}_rcsid[] = {rcs};")?;
    writeln!(w, "#else\t/* UseExternRCSId */")?;
    writeln!(w, "static const char rcsid[] = {rcs};")?;
    writeln!(w, "#endif\t/* UseExternRCSId */")?;
    writeln!(w, "#endif\t/* lint */")?;
    writeln!(w)
}

/// `WriteApplDefaults`
pub fn write_appl_defaults(w: &mut dyn Write, dir: &str) -> io::Result<()> {
    for (w1, w3) in [
        ("Declare", "Rpc"),
        ("Before", "Rpc"),
        ("After", "Rpc"),
        ("Declare", "Simple"),
        ("Before", "Simple"),
        ("After", "Simple"),
    ] {
        let buf = format!("__{w1}{dir}{w3}");
        writeln!(w, "#ifndef\t{buf}")?;
        writeln!(w, "#define\t{buf}(_NUM_, _NAME_)")?;
        writeln!(w, "#endif\t/* {buf} */")?;
        writeln!(w)?;
    }
    Ok(())
}

/// `WriteApplMacro`
pub fn write_appl_macro(
    w: &mut dyn Write,
    g: &Gen,
    dir: &str,
    when: &str,
    rt: &Routine,
) -> io::Result<()> {
    let what = if rt.one_way { "Simple" } else { "Rpc" };
    writeln!(
        w,
        "\t__{when}{dir}{what}({}, \"{}\")",
        g.opts.subsystem_base + rt.number,
        rt.name
    )
}

